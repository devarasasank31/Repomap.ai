-- Symbols extracted from imported sources (classes, methods, functions, ...)
-- and the HTTP endpoints detected in Spring / Express / NestJS style code.

CREATE TABLE symbols (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id     BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    file_id        BIGINT       REFERENCES project_files (id) ON DELETE SET NULL,
    path           VARCHAR(1024) NOT NULL,
    kind           VARCHAR(32)  NOT NULL,
    name           VARCHAR(255) NOT NULL,
    qualified_name VARCHAR(512),
    signature      VARCHAR(1000),
    parent_name    VARCHAR(255),
    annotations    VARCHAR(2000),
    line_start     INTEGER      NOT NULL DEFAULT 0,
    line_end       INTEGER      NOT NULL DEFAULT 0
);

CREATE INDEX idx_symbols_project ON symbols (project_id);
CREATE INDEX idx_symbols_project_kind ON symbols (project_id, kind);
CREATE INDEX idx_symbols_project_name ON symbols (project_id, name);

CREATE TABLE endpoints (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    file_id     BIGINT       REFERENCES project_files (id) ON DELETE SET NULL,
    path        VARCHAR(1024) NOT NULL,
    http_method VARCHAR(16)  NOT NULL,
    handler     VARCHAR(512),
    class_name  VARCHAR(255),
    line_start  INTEGER      NOT NULL DEFAULT 0
);

CREATE INDEX idx_endpoints_project ON endpoints (project_id);
CREATE INDEX idx_endpoints_project_method ON endpoints (project_id, http_method);
