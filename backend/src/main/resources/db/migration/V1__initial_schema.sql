-- RepoMap.ai initial schema
-- Portable across PostgreSQL (runtime) and H2 in PostgreSQL mode (tests).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(120) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_users_username ON users (username);
CREATE UNIQUE INDEX uq_users_email ON users (email);

-- Opaque bearer tokens are stored as SHA-256 hashes, never in plain text.
CREATE TABLE auth_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_auth_tokens_hash ON auth_tokens (token_hash);
CREATE INDEX idx_auth_tokens_user ON auth_tokens (user_id);
CREATE INDEX idx_auth_tokens_expires ON auth_tokens (expires_at);

CREATE TABLE projects (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id          BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name              VARCHAR(200) NOT NULL,
    description       VARCHAR(1000),
    status            VARCHAR(32)  NOT NULL DEFAULT 'CREATED',
    source_filename   VARCHAR(255),
    storage_key       VARCHAR(64)  NOT NULL,
    file_count        INTEGER      NOT NULL DEFAULT 0,
    total_size_bytes  BIGINT       NOT NULL DEFAULT 0,
    java_file_count   INTEGER      NOT NULL DEFAULT 0,
    class_count       INTEGER      NOT NULL DEFAULT 0,
    method_count      INTEGER      NOT NULL DEFAULT 0,
    endpoint_count    INTEGER      NOT NULL DEFAULT 0,
    error_message     VARCHAR(2000),
    created_at        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP
);

CREATE INDEX idx_projects_owner ON projects (owner_id);
CREATE UNIQUE INDEX uq_projects_storage_key ON projects (storage_key);

CREATE TABLE project_files (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    path       VARCHAR(1024) NOT NULL,
    directory  VARCHAR(768)  NOT NULL DEFAULT '',
    filename   VARCHAR(255)  NOT NULL,
    extension  VARCHAR(32),
    language   VARCHAR(32),
    size_bytes BIGINT       NOT NULL DEFAULT 0,
    line_count INTEGER      NOT NULL DEFAULT 0,
    analyzed   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_project_files_project ON project_files (project_id);
CREATE INDEX idx_project_files_language ON project_files (project_id, language);
CREATE UNIQUE INDEX uq_project_files_path ON project_files (project_id, path);
